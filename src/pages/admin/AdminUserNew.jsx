// AdminUserNew — wired to POST /api/admin/users + GET /api/admin/categories.
// Per docs/pages/15-admin-user-new.md.

import { useMemo, useState } from 'react'
import { useNavigate } from 'react-router-dom'
import { Sparkles, RefreshCw, CheckCircle2 } from 'lucide-react'

import { AdminTopBar } from '../../components/layout/AdminTopBar.jsx'
import { Card } from '../../components/ui/Card.jsx'
import { Container } from '../../components/ui/Container.jsx'
import { FormError } from '../../components/ui/FormError.jsx'
import { GhostButton } from '../../components/ui/GhostButton.jsx'
import { InlineAlert } from '../../components/ui/InlineAlert.jsx'
import { Modal } from '../../components/ui/Modal.jsx'
import { MultiSelect } from '../../components/ui/MultiSelect.jsx'
import { PrimaryButton } from '../../components/ui/PrimaryButton.jsx'
import { ProgressBar } from '../../components/ui/ProgressBar.jsx'
import { RadioGroup } from '../../components/ui/RadioGroup.jsx'
import { Stack } from '../../components/ui/Stack.jsx'
import { Switch } from '../../components/ui/Switch.jsx'
import { TextInput } from '../../components/ui/TextInput.jsx'

import {
  generatePassword,
  passwordStrength,
  STRENGTH_LABELS,
  STRENGTH_VARIANTS,
} from '../../lib/password.js'

import { listCategories } from '../../lib/api/admin-categories.js'
import { createUser } from '../../lib/api/admin-users.js'
import { useQuery } from '../../lib/hooks/useApi.js'
import { ApiError } from '../../lib/api.js'

const ROLE_OPTIONS = [
  { value: 'USER',  label: 'User',  description: 'Standard access — can post intake/expense and close their day' },
  { value: 'ADMIN', label: 'Admin', description: 'Full access including user management and reports' },
]

const MAX_CATEGORIES = 5

// Validation patterns — match backend validators.
const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/
const USERNAME_RE = /^[a-zA-Z0-9_]+$/
const PHONE_RE = /^\+?[0-9\s\-()]{7,20}$/

const initialValues = {
  email: '',
  username: '',
  name: '',
  phone: '',
  role: 'USER',
  categories: [],
  password: '',
  isActive: true,
}

function validate(values) {
  const errors = {}

  if (!values.email.trim()) {
    errors.email = 'Email is required'
  } else if (!EMAIL_RE.test(values.email.trim())) {
    errors.email = 'Enter a valid email address'
  }

  if (!values.username.trim()) {
    errors.username = 'Username is required'
  } else if (values.username.length < 3 || values.username.length > 30) {
    errors.username = 'Username must be 3–30 characters'
  } else if (!USERNAME_RE.test(values.username)) {
    errors.username = 'Only letters, numbers, and underscores'
  }

  if (!values.name.trim()) {
    errors.name = 'Name is required'
  } else if (values.name.length > 100) {
    errors.name = 'Name must be 100 characters or fewer'
  }

  if (values.phone && !PHONE_RE.test(values.phone)) {
    errors.phone = 'Enter a valid phone number (7–15 digits, optional + prefix)'
  }

  if (values.role === 'USER' && values.categories.length === 0) {
    errors.categories = 'Assign at least 1 category for User role'
  }

  if (!values.password) {
    errors.password = 'Password is required'
  } else if (values.password.length < 8) {
    errors.password = 'Password must be at least 8 characters'
  }

  return errors
}

export default function AdminUserNew() {
  const navigate = useNavigate()

  const catQ = useQuery(() => listCategories({}), [])
  const categoryOptions = useMemo(
    () => (catQ.data?.categories ?? []).map((c) => ({ value: c.id, label: c.name })),
    [catQ.data],
  )

  const [values, setValues] = useState(initialValues)
  const [errors, setErrors] = useState({})
  const [isSubmitting, setIsSubmitting] = useState(false)
  const [successModalOpen, setSuccessModalOpen] = useState(false)
  const [createdPassword, setCreatedPassword] = useState('')
  const [createdUsername, setCreatedUsername] = useState('')
  const [copyAnnouncement, setCopyAnnouncement] = useState('')
  const [passwordAutoGenerated, setPasswordAutoGenerated] = useState(false)
  const [submitError, setSubmitError] = useState(null)

  const strength = passwordStrength(values.password)

  const update = (key) => (e) => {
    const next = typeof e === 'string' || typeof e === 'boolean' ? e : e.target.value
    setValues((prev) => ({ ...prev, [key]: next }))
    setErrors((prev) => {
      if (!prev[key]) return prev
      const { [key]: _drop, ...rest } = prev
      return rest
    })
  }

  const handleAutoGenerate = () => {
    const pw = generatePassword(16)
    setValues((prev) => ({ ...prev, password: pw }))
    setPasswordAutoGenerated(true)
    setErrors((prev) => {
      if (!prev.password) return prev
      const { password: _drop, ...rest } = prev
      return rest
    })
  }

  const handleSubmit = async (e) => {
    e.preventDefault()
    setSubmitError(null)
    const v = validate(values)
    setErrors(v)
    if (Object.keys(v).length > 0) {
      const firstKey = Object.keys(v)[0]
      const el = document.getElementById(`field-${firstKey}`)
      el?.focus?.()
      return
    }

    setIsSubmitting(true)
    try {
      await createUser({
        email: values.email.trim(),
        username: values.username.trim(),
        name: values.name.trim(),
        phone: values.phone.trim() || undefined,
        role: values.role,
        categoryIds: values.categories,
        password: values.password,
        isActive: values.isActive,
      })
      setCreatedUsername(values.username)
      setCreatedPassword(values.password)
      setSuccessModalOpen(true)
    } catch (err) {
      if (err instanceof ApiError) {
        if (err.code === 'duplicate_email') {
          setErrors((prev) => ({ ...prev, email: 'Email already in use' }))
        } else if (err.code === 'duplicate_username') {
          setErrors((prev) => ({ ...prev, username: 'Username already taken' }))
        } else if (err.code === 'invalid_category_ids') {
          setErrors((prev) => ({ ...prev, categories: 'One or more categories don\u2019t exist' }))
        } else if (err.fields) {
          // Surface first field-level error.
          const firstField = Object.keys(err.fields)[0]
          setErrors((prev) => ({ ...prev, [firstField]: err.fields[firstField][0] }))
        } else {
          setSubmitError(err.message || 'Couldn\u2019t create user.')
        }
      } else {
        setSubmitError(err?.message || 'Couldn\u2019t create user.')
      }
    } finally {
      setIsSubmitting(false)
    }
  }

  const handleCloseSuccess = () => {
    setSuccessModalOpen(false)
    navigate('/admin/users')
  }

  const handleCopyPassword = async () => {
    try {
      await navigator.clipboard.writeText(createdPassword)
      setCopyAnnouncement('Password copied to clipboard')
      setTimeout(() => setCopyAnnouncement(''), 2500)
    } catch {
      setCopyAnnouncement('Copy failed — select the password manually')
      setTimeout(() => setCopyAnnouncement(''), 2500)
    }
  }

  const errorSummary =
    Object.keys(errors).length > 0
      ? `Please fix ${Object.keys(errors).length} field${Object.keys(errors).length > 1 ? 's' : ''} above.`
      : ''

  return (
    <div className="flex min-h-screen flex-col bg-bg-page text-text-primary">
      <AdminTopBar title="New user" back="/admin/users" />

      <main aria-label="Create new user" className="flex-1">
        <Container className="py-4 sm:py-6">
          <form onSubmit={handleSubmit} noValidate>
            <Stack gap={4}>
              {submitError && (
                <InlineAlert variant="danger" title="Couldn't create user">
                  {submitError}
                </InlineAlert>
              )}

              {errorSummary && (
                <FormError
                  title="Form has errors"
                  message={errorSummary}
                />
              )}

              <Card padding="lg">
                <Stack gap={4}>
                  <TextInput
                    id="field-email"
                    label="Email"
                    type="email"
                    autoComplete="email"
                    required
                    value={values.email}
                    onChange={update('email')}
                    error={errors.email}
                    placeholder="name@example.org"
                  />

                  <TextInput
                    id="field-username"
                    label="Username"
                    type="text"
                    autoComplete="username"
                    required
                    value={values.username}
                    onChange={update('username')}
                    error={errors.username}
                    helperText="3–30 characters · letters, numbers, and underscores"
                    placeholder="e.g. aisha"
                  />

                  <TextInput
                    id="field-name"
                    label="Full name"
                    type="text"
                    autoComplete="name"
                    required
                    value={values.name}
                    onChange={update('name')}
                    error={errors.name}
                    placeholder="e.g. Aisha Khan"
                  />

                  <TextInput
                    id="field-phone"
                    label="Phone"
                    type="tel"
                    autoComplete="tel"
                    value={values.phone}
                    onChange={update('phone')}
                    error={errors.phone}
                    helperText="Optional · 7–15 digits, optional + prefix"
                    placeholder="+923001234567"
                  />

                  <RadioGroup
                    name="role"
                    label="Role"
                    value={values.role}
                    onChange={(v) => {
                      setValues((prev) => ({ ...prev, role: v }))
                      setErrors((prev) => {
                        if (!prev.categories && !prev.role) return prev
                        const { categories: _drop, role: _drop2, ...rest } = prev
                        return rest
                      })
                    }}
                    options={ROLE_OPTIONS}
                  />

                  <div>
                    <MultiSelect
                      label={
                        values.role === 'ADMIN'
                          ? 'Categories (optional for admins)'
                          : 'Categories'
                      }
                      options={categoryOptions}
                      value={values.categories}
                      onChange={(next) => {
                        const capped = next.length > MAX_CATEGORIES ? next.slice(0, MAX_CATEGORIES) : next
                        setValues((prev) => ({ ...prev, categories: capped }))
                        setErrors((prev) => {
                          if (!prev.categories) return prev
                          const { categories: _drop, ...rest } = prev
                          return rest
                        })
                      }}
                      placeholder={categoryOptions.length === 0 ? 'Loading categories…' : 'Select categories…'}
                      disabled={categoryOptions.length === 0}
                    />
                    <p className={`mt-1 text-caption ${errors.categories ? 'text-danger-700' : 'text-text-tertiary'}`}>
                      {errors.categories || `Up to ${MAX_CATEGORIES} categories`}
                    </p>
                  </div>

                  <Card variant="filled" padding="md" className="flex flex-col gap-3">
                    <div className="flex items-center justify-between gap-2">
                      <h3 className="text-body-l font-semibold text-text-primary">Password</h3>
                      <GhostButton
                        type="button"
                        onClick={handleAutoGenerate}
                        aria-label="Generate random password"
                      >
                        <Sparkles className="h-4 w-4" aria-hidden="true" />
                        <span>Auto-generate</span>
                        <RefreshCw className="h-4 w-4" aria-hidden="true" />
                      </GhostButton>
                    </div>

                    <TextInput
                      id="field-password"
                      label="Set a password"
                      type="password"
                      autoComplete="new-password"
                      value={values.password}
                      onChange={update('password')}
                      error={errors.password}
                      helperText="Shown in clear text (admin context). User can rotate after first login."
                      placeholder="At least 8 characters"
                    />

                    {values.password && (
                      <ProgressBar
                        value={strength}
                        max={4}
                        label="Strength"
                        trailing={STRENGTH_LABELS[strength]}
                        variant={STRENGTH_VARIANTS[strength]}
                      />
                    )}
                  </Card>

                  <div className="flex items-center justify-between gap-3 rounded-lg border border-border-strong bg-bg-surface px-3 py-2">
                    <div className="flex flex-col">
                      <span className="text-body-m font-medium text-text-primary">
                        Active on creation
                      </span>
                      <span className="text-caption text-text-tertiary">
                        Inactive users cannot sign in until reactivated.
                      </span>
                    </div>
                    <Switch
                      checked={values.isActive}
                      onChange={(next) => setValues((prev) => ({ ...prev, isActive: next }))}
                      aria-label="Active on creation"
                    />
                  </div>
                </Stack>
              </Card>
            </Stack>

            <div className="sticky bottom-0 z-sticky mt-6 -mx-4 border-t border-border bg-bg-surface px-4 py-3 sm:-mx-6 sm:px-6">
              <div className="mx-auto flex max-w-3xl flex-col-reverse items-stretch gap-2 sm:flex-row sm:items-center sm:justify-end">
                <GhostButton
                  type="button"
                  onClick={() => navigate('/admin/users')}
                  disabled={isSubmitting}
                >
                  Cancel
                </GhostButton>
                <div className="sm:flex-1">
                  <PrimaryButton
                    type="submit"
                    fullWidth
                    disabled={isSubmitting}
                  >
                    {isSubmitting ? 'Creating…' : 'Create user'}
                  </PrimaryButton>
                </div>
              </div>
            </div>
          </form>
        </Container>
      </main>

      <p role="status" aria-live="polite" className="sr-only">
        {copyAnnouncement}
      </p>

      <Modal
        open={successModalOpen}
        onClose={handleCloseSuccess}
        title="User created"
        size="md"
      >
        <Stack gap={4}>
          <div className="flex items-center justify-center">
            <span className="inline-flex h-14 w-14 items-center justify-center rounded-full bg-success-50 text-success-700">
              <CheckCircle2 className="h-8 w-8" aria-hidden="true" />
            </span>
          </div>

          <div className="rounded-lg border border-border-strong bg-bg-sunken px-4 py-3 font-mono text-body-m text-text-primary">
            <p>
              <span className="text-text-tertiary">Username:</span> {createdUsername}
            </p>
            <p>
              <span className="text-text-tertiary">Password:</span> {createdPassword}
            </p>
          </div>

          <InlineAlert variant="warning" title="Save this password now">
            This password will not be shown again. Share it securely.
            {!passwordAutoGenerated && (
              <p className="mt-1">
                Note: this password was entered manually — confirm with the user they received it.
              </p>
            )}
          </InlineAlert>

          <div className="flex flex-col gap-2 sm:flex-row sm:justify-end">
            <GhostButton type="button" onClick={handleCopyPassword}>
              Copy password
            </GhostButton>
            <PrimaryButton type="button" onClick={handleCloseSuccess}>
              Close
            </PrimaryButton>
          </div>
        </Stack>
      </Modal>
    </div>
  )
}